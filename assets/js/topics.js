// Topics that match the teacher's text, best first.
export function suggestTopics(text, max = 4) {
  const t = String(text).toLowerCase();
  return TOPICS.map((x) => ({ x, n: x.keys.filter((k) => t.includes(k)).length }))
    .filter((r) => r.n > 0).sort((a, b) => b.n - a.n).slice(0, max).map((r) => r.x);
}
